// Generates frontend/icons.js from the Phosphor icon set (npm i -D @phosphor-icons/core).
// The frontend inlines these as <svg>, so the standalone file needs no network and no icon font.
// Run: node scripts/build-icons.js
const fs = require("fs");
const path = require("path");

const NAMES = [
  "factory", "truck", "warehouse", "storefront", "user-circle", "package", "plus-circle", "path",
  "shield-check", "magnifying-glass", "arrow-clockwise", "x", "copy", "check", "check-circle",
  "cube", "warning-octagon", "arrow-u-up-left", "arrow-right", "arrow-left", "map-pin", "clock", "wallet", "seal-check",
  "compass", "play", "bag", "info", "crown", "eye", "link", "warning",
];

const dir = path.join(__dirname, "../node_modules/@phosphor-icons/core/assets/regular");
const out = {};
for (const n of NAMES) {
  const f = path.join(dir, n + ".svg");
  if (!fs.existsSync(f)) { console.error("missing icon:", n); process.exit(1); }
  const svg = fs.readFileSync(f, "utf8");
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
}
const body = `// Generated by scripts/build-icons.js from @phosphor-icons/core (MIT). Do not edit by hand.\nwindow.ICONS = ${JSON.stringify(out)};\n`;
fs.writeFileSync(path.join(__dirname, "../frontend/icons.js"), body);
console.log("Wrote frontend/icons.js with", NAMES.length, "icons");
